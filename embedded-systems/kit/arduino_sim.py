#!/usr/bin/env python3
"""arduino_sim.py -- build and run Arduino sketches on this computer, offline.

    python3 arduino_sim.py run  sketch.ino [--scenario file] [--duration ms] [--wave] [--json]
    python3 arduino_sim.py run  a.ino --board2 b.ino --link      (two boards, Serial crossed)
    python3 arduino_sim.py avr  sketch.ino                        (compile for the real ATmega328P if avr-g++ exists)

The sketch is compiled with clang++ against sim/Arduino.h (a host emulation of
the Arduino Uno API), run against a scenario (button presses, serial input), and
the resulting trace is printed as a timeline of pin changes and Serial output.
check.py uses the same machinery to grade exercises.
"""
import argparse, json, os, re, subprocess, sys, tempfile, hashlib, shutil

KIT = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.join(KIT, "sim")
BUILD = os.path.join(KIT, "build")
os.makedirs(BUILD, exist_ok=True)

KEYWORDS = {"if", "while", "for", "switch", "return", "else", "do", "sizeof", "case", "catch"}

BUILTIN_TYPES = {"void", "int", "unsigned", "signed", "long", "short", "char", "bool", "boolean", "byte", "float", "double",
                 "uint8_t", "uint16_t", "uint32_t", "int8_t", "int16_t", "int32_t", "size_t", "const", "String", "static", "inline", "word"}

def add_prototypes(src: str) -> str:
    """Mimic the Arduino builders: generate a prototype for every top-level function so that
    functions can be used before they are defined. Prototypes that only use built-in types go
    to the top of the file (as Tinkercad does); prototypes using user-defined types (enum class,
    struct) are inserted just before the first function definition, after those types exist."""
    scan = re.sub(r"//[^\n]*", lambda m: " " * len(m.group(0)), src)
    scan = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), scan, flags=re.S)
    scan = re.sub(r'"(\\.|[^"\\])*"', lambda m: " " * len(m.group(0)), scan)
    depth = 0; i = 0; simple = []; complex_ = []; first_def = None
    pat = re.compile(r"([A-Za-z_][\w:<>,\s\*&]*?[\w>\*&])\s+(\*?\s*[A-Za-z_]\w*)\s*\(([^;{}()]*)\)\s*(const)?\s*\{")
    while i < len(scan):
        c = scan[i]
        if c == "{": depth += 1; i += 1; continue
        if c == "}": depth -= 1; i += 1; continue
        if depth == 0:
            m = pat.match(scan, i)
            if m:
                ret, name, args = m.group(1).strip(), m.group(2).strip(), m.group(3)
                name_clean = name.lstrip("*").strip()
                words = ret.split()
                if name_clean not in KEYWORDS and words and words[0] not in KEYWORDS and "=" not in ret \
                        and not ret.startswith(("enum", "struct", "class", "namespace")) and ret.split()[-1] != "return":
                    if first_def is None: first_def = m.start()
                    args_p = re.sub(r"=\s*[^,]+", "", args)
                    proto = f"{ret} {name}({args_p.strip()});"
                    idents = set(re.findall(r"[A-Za-z_]\w*", ret + " " + re.sub(r"[A-Za-z_]\w*\s*(?=,|$)", "", args_p)))
                    (simple if idents <= BUILTIN_TYPES else complex_).append(proto)
                i = m.end() - 1
                continue
        i += 1
    if first_def is None:
        return src
    out = src
    if complex_:
        out = out[:first_def] + "\n// --- prototypes (user types) generated by arduino_sim.py ---\n" + "\n".join(complex_) + "\n\n" + out[first_def:]
    if simple:
        # after the last #include at the top of the file
        m = None
        for m in re.finditer(r"^[ \t]*#include[^\n]*\n", out, flags=re.M): pass
        pos = m.end() if m else 0
        out = out[:pos] + "// --- prototypes generated by arduino_sim.py (the Arduino IDE/Tinkercad do the same) ---\n" + "\n".join(simple) + "\n" + out[pos:]
    return out

def prepare_ino(path: str, tag: str) -> str:
    src = open(path, encoding="utf-8", errors="replace").read()
    out = os.path.join(BUILD, f"{tag}.ino.cpp")
    open(out, "w").write(add_prototypes(src))
    return out

def build(sketches, tag=None):
    """sketches: list of .ino paths (1 or 2). Returns path of executable."""
    key = hashlib.md5(("|".join(os.path.abspath(s) for s in sketches) + open(os.path.join(SIM, "Arduino.h")).read()).encode()).hexdigest()[:10]
    tag = tag or ("sk_" + key)
    main_cpp = os.path.join(BUILD, f"{tag}_main.cpp")
    parts = ['#include "Arduino.h"', "namespace sim { void registerBoard(int, void(*)(), void(*)()); int run(int, char**); }"]
    for i, s in enumerate(sketches):
        pre = prepare_ino(s, f"{tag}_b{i}")
        parts.append(f"namespace board{i} {{\nBOARD_API({i})\n#include \"{pre}\"\n}}")
    parts.append("int main(int argc, char** argv) {")
    for i in range(len(sketches)):
        parts.append(f"  sim::registerBoard({i}, board{i}::setup, board{i}::loop);")
    parts.append("  return sim::run(argc, argv);\n}")
    open(main_cpp, "w").write("\n".join(parts) + "\n")
    exe = os.path.join(BUILD, tag)
    srcs = [main_cpp, os.path.join(SIM, "sim.cpp")]
    newest = max(os.path.getmtime(p) for p in srcs + [os.path.join(SIM, "Arduino.h")] + sketches)
    if os.path.exists(exe) and os.path.getmtime(exe) > newest:
        return exe, ""
    cmd = ["clang++", "-std=c++17", "-O1", "-w", "-I", SIM, "-x", "c++", main_cpp, os.path.join(SIM, "sim.cpp"), "-o", exe, "-lpthread"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        return None, clean_errors(r.stderr, sketches)
    return exe, ""

def clean_errors(stderr: str, sketches):
    """Rewrite compiler messages so they point at the user's .ino line numbers."""
    out = []
    for line in stderr.splitlines():
        m = re.match(r"(.*?)_b(\d+)\.ino\.cpp:(\d+):(\d+): (.*)", line)
        if m:
            i, ln, col, msg = int(m.group(2)), int(m.group(3)), m.group(4), m.group(5)
            pre = open(os.path.join(BUILD, os.path.basename(m.group(1)) + f"_b{i}.ino.cpp")).read().splitlines() if False else None
            out.append(f"{os.path.basename(sketches[i])}:{ln}:{col}: {msg}")
        elif "_main.cpp" in line or line.startswith("In file included") or line.startswith("namespace board"):
            continue
        else:
            out.append(line)
    text = "\n".join(out)
    text = re.sub(r"board\d+::", "", text)
    return text

def write_scenario(duration_ms=10000, events=(), link=False, tick_us=100, seed=12345):
    """events: list of dicts {t, board, kind, pin, value, bounce, text, ...}"""
    lines = [f"duration {duration_ms}", f"tick {tick_us}", f"seed {seed}"]
    if link: lines.append("link 0 1")
    for e in events:
        b = e.get("board", 0); k = e["kind"]
        if k == "pin":
            l = f"at {e['t']} pin {b} {e['pin']} {e['value']}"
            if e.get("bounce"): l += f" bounce {e['bounce']}"
        elif k == "release": l = f"at {e['t']} release {b} {e['pin']}"
        elif k == "analog": l = f"at {e['t']} analog {b} {e['pin']} {e['value']}"
        elif k == "serial":
            txt = e["text"].encode("unicode_escape").decode("ascii").replace("\\x00", "\\0")
            l = f"at {e['t']} serial {b} {txt}"
        else: continue
        lines.append(l)
    fd, path = tempfile.mkstemp(prefix="scn_", suffix=".txt", dir=BUILD)
    with os.fdopen(fd, "w") as f: f.write("\n".join(lines) + "\n")
    return path

def run(exe, scenario_path, timeout=60):
    r = subprocess.run([exe, scenario_path], capture_output=True, text=True, timeout=timeout)
    try:
        return json.loads(r.stdout)
    except json.JSONDecodeError:
        raise RuntimeError("simulator produced no trace:\n" + r.stdout[-2000:] + r.stderr[-2000:])

# ---------- helpers for reading a trace ----------
def serial_text(trace, board=0):
    return "".join(e["text"] for e in trace["events"] if e["kind"] == "tx" and e["board"] == board)

def serial_lines(trace, board=0):
    return [l for l in serial_text(trace, board).replace("\r\n", "\n").split("\n")]

def serial_chunks(trace, board=0):
    """list of (t, text, bytes) per write call"""
    return [(e["t"], e["text"], e["bytes"]) for e in trace["events"] if e["kind"] == "tx" and e["board"] == board]

def pin_changes(trace, pin, board=0):
    """list of (t, value) for every traced level change of an OUTPUT pin"""
    return [(e["t"], e["value"]) for e in trace["events"] if e["kind"] == "pin" and e["pin"] == pin and e["board"] == board]

def pin_level_at(trace, pin, t, board=0):
    v = None
    for tt, val in pin_changes(trace, pin, board):
        if tt <= t: v = val
        else: break
    return v

def pwm_changes(trace, pin, board=0):
    return [(e["t"], e["value"]) for e in trace["events"] if e["kind"] == "pwm" and e["pin"] == pin and e["board"] == board]

def pin_modes(trace, board=0):
    m = {}
    for e in trace["events"]:
        if e["kind"] == "pinMode" and e["board"] == board: m[e["pin"]] = e["mode"]
    return m

def warnings(trace):
    return [(e["t"], e["msg"]) for e in trace["events"] if e["kind"] == "warn"]

def intervals(changes, duration):
    """From [(t,v)...] produce [(t_start, t_end, v)] segments."""
    segs = []
    for i, (t, v) in enumerate(changes):
        t_end = changes[i + 1][0] if i + 1 < len(changes) else duration
        segs.append((t, t_end, v))
    return segs

def ascii_wave(trace, pins=None, width=100, board=0):
    dur = trace["end_ms"]
    if pins is None:
        pins = sorted({e["pin"] for e in trace["events"] if e["kind"] in ("pin", "input") and e["board"] == board})
    lines = []
    for p in pins:
        ch = pin_changes(trace, p, board)
        inp = [(e["t"], e["value"]) for e in trace["events"] if e["kind"] == "input" and e["pin"] == p and e["board"] == board and isinstance(e["value"], int)]
        src = ch if ch else inp
        row = []
        for i in range(width):
            t = dur * i / width
            v = None
            for tt, val in src:
                if tt <= t: v = val
                else: break
            row.append("#" if v == 1 else ("_" if v == 0 else "."))
        kind = "out" if ch else "in "
        lines.append(f"pin {p:2d} {kind} |{''.join(row)}|")
    lines.append(f"          0 ms {' ' * (width - 12)}{dur:.0f} ms")
    return "\n".join(lines)

def print_timeline(trace, board=None, max_lines=400):
    n = 0
    for e in trace["events"]:
        if board is not None and e["board"] != board: continue
        b = f"[B{e['board']}] " if trace["boards"] > 1 else ""
        t = f"{e['t']:9.1f} ms  "
        k = e["kind"]
        if k == "pin": s = f"pin {e['pin']} -> {'HIGH' if e['value'] else 'LOW'}"
        elif k == "pwm": s = f"pin {e['pin']} PWM {e['value']}/255"
        elif k == "pinMode": s = f"pinMode({e['pin']}, {e['mode']})" + (" via register" if e.get("via") else "")
        elif k == "tx": s = f"Serial out: {e['text']!r}" + ("" if e["printable"] else f"  bytes={e['bytes']}")
        elif k == "rx": s = f"Serial in : {e['text']!r}"
        elif k == "input": s = f"input pin {e['pin']} = {e.get('value', e.get('analog'))}"
        elif k == "tone": s = f"tone pin {e['pin']} {e['freq']} Hz" if e["freq"] else f"noTone pin {e['pin']}"
        elif k == "delay": s = f"delay({e['ms']})  (CPU blocked)"
        elif k == "serialBegin": s = f"Serial.begin({e['baud']})"
        elif k == "warn": s = f"WARNING: {e['msg']}"
        else: s = json.dumps(e)
        print(t + b + s); n += 1
        if n >= max_lines: print(f"... ({len(trace['events']) - n} more events)"); break

def avr_compile(sketch):
    avr = shutil.which("avr-g++") or next((p for p in ["/opt/homebrew/opt/avr-gcc@14/bin/avr-g++", "/usr/local/bin/avr-g++"] if os.path.exists(p)), None)
    if not avr:
        print("avr-g++ not installed; skipping real-target compilation."); return 1
    core = os.path.join(KIT, "avr-core")
    pre = prepare_ino(sketch, "avr")
    cmd = [avr, "-std=gnu++17", "-mmcu=atmega328p", "-DF_CPU=16000000UL", "-Os", "-fsyntax-only", "-Wall", "-Wextra", "-Wno-unused-parameter", "-I", core, "-include", "Arduino.h", "-x", "c++", pre]
    r = subprocess.run(cmd, capture_output=True, text=True)
    print(r.stderr or "avr-g++: syntax OK for ATmega328P")
    return r.returncode

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run"); r.add_argument("sketch"); r.add_argument("--board2"); r.add_argument("--link", action="store_true")
    r.add_argument("--scenario"); r.add_argument("--duration", type=float, default=10000); r.add_argument("--wave", action="store_true")
    r.add_argument("--json", action="store_true"); r.add_argument("--press", action="append", default=[], help="t:pin[:ms] simulate a button press (active LOW) at t for ms (default 200)")
    r.add_argument("--serial", action="append", default=[], help="t:text send text to the board at t ms")
    a = sub.add_parser("avr"); a.add_argument("sketch")
    args = ap.parse_args()
    if args.cmd == "avr":
        sys.exit(avr_compile(args.sketch))
    sketches = [args.sketch] + ([args.board2] if args.board2 else [])
    exe, err = build(sketches)
    if not exe:
        print(err); sys.exit(1)
    if args.scenario:
        scn = args.scenario
    else:
        ev = []
        for p in args.press:
            parts = p.split(":"); t = float(parts[0]); pin = int(parts[1]); ms = float(parts[2]) if len(parts) > 2 else 200
            ev.append({"t": t, "kind": "pin", "pin": pin, "value": 0, "bounce": 5}); ev.append({"t": t + ms, "kind": "pin", "pin": pin, "value": 1, "bounce": 5})
        for s in args.serial:
            t, txt = s.split(":", 1); ev.append({"t": float(t), "kind": "serial", "text": txt.encode().decode("unicode_escape")})
        scn = write_scenario(args.duration, ev, link=args.link or bool(args.board2))
    trace = run(exe, scn)
    if args.json:
        print(json.dumps(trace, indent=1)); return
    print_timeline(trace)
    if args.wave:
        print(); print(ascii_wave(trace))
    w = warnings(trace)
    print(f"\n{len(trace['events'])} events, {len(w)} warnings, simulated {trace['end_ms']:.0f} ms")

if __name__ == "__main__":
    main()
